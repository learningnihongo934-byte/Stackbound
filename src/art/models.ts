const cache = new Map<string, VoxelModel>();
export function getModel(id: string): VoxelModel {
  let m = cache.get(id);
  if (!m) {
    const s = MODELS[id];
    if (!s) throw new Error('no model for ' + id);
    m = buildModel(id, s.pal, s.src);
    cache.set(id, m);
  }
  return m;
}
